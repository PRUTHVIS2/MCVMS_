"""Synthetic detector for evaluating synthetic test clips.

Detects colored boxes generated by make_synthetic_clip / generate_synthetic_data:
- Red (0, 0, 255) -> truck
- Blue (255, 0, 0) -> car
- Green (0, 255, 0) -> person

Zero GPU, pure OpenCV contour extraction.
"""


import cv2
import numpy as np

from app.core.types import Detection


class SyntheticBoxDetector:
    """Detects colored rectangular boxes on a neutral background."""

    def __init__(self, bg_val: int = 50):
        self.bg_val = bg_val

    def detect(self, frames: np.ndarray | list[np.ndarray], conf: float = 0.25) -> list[Detection] | list[list[Detection]]:
        is_single = not isinstance(frames, list)
        if is_single:
            frames = [frames]

        batch_results: list[list[Detection]] = []

        for frame in frames:
            detections: list[Detection] = []
            if frame is None or frame.size == 0:
                batch_results.append(detections)
                continue

            bg = np.array([self.bg_val, self.bg_val, self.bg_val], dtype=np.uint8)
            diff = cv2.absdiff(frame, bg)
            gray = cv2.cvtColor(diff, cv2.COLOR_BGR2GRAY)
            _, thresh = cv2.threshold(gray, 30, 255, cv2.THRESH_BINARY)

            contours, _ = cv2.findContours(thresh, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)

            for cnt in contours:
                if cv2.contourArea(cnt) < 100:
                    continue

                x, y, w, h = cv2.boundingRect(cnt)
                roi = frame[y:y+h, x:x+w]
                b_mean, g_mean, r_mean = np.mean(roi, axis=(0, 1))

                # Identify class by dominant BGR channel
                if r_mean > 150 and b_mean < 80:
                    cls_name = "truck"
                elif b_mean > 150 and r_mean < 80:
                    cls_name = "car"
                elif g_mean > 150:
                    cls_name = "person"
                else:
                    cls_name = "car"

                detections.append(Detection(
                    cls=cls_name,
                    conf=0.95,
                    xyxy=(float(x), float(y), float(x + w), float(y + h))
                ))

            batch_results.append(detections)

        return batch_results[0] if is_single else batch_results
